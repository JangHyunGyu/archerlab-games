export function translation(locale) {
    return (key, values = {}) => {
        const value = messages[locale]?.[key];
        if (value === undefined) throw new Error(`Missing translation: ${locale}.${key}`);
        return value.replace(/\{([^}]+)\}/g, (_, name) => String(values[name] ?? ''));
    };
}
