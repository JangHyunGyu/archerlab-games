const paired = (rows) => rows.flatMap(([answerId, koYes, enYes, koNo, enNo]) => [
  { answerId, ko: koYes, en: enYes, expected: 'yes' },
  { answerId, ko: koNo, en: enNo, expected: 'no' },
]);
const alternating = (rows, first = 'yes') => rows.map(([answerId, ko, en], index) => ({
  answerId, ko, en, expected: index % 2 === 0 ? first : first === 'yes' ? 'no' : 'yes',
}));
const labeled = (rows, expected) => rows.map(([answerId, ko, en]) => ({ answerId, ko, en, expected }));

